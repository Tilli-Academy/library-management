-- PageTurn schema. Rules are enforced by the database too (CHECK / UNIQUE / FOREIGN KEY),
-- so even a bug in the Java code cannot store impossible data.

CREATE TABLE users (
    id             UUID         PRIMARY KEY,
    email          VARCHAR(320) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    display_name   VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL CHECK (role IN ('MEMBER', 'LIBRARIAN')),
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    -- Increased on sign-out; tokens issued before that stop working.
    token_version  INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT users_email_lowercase CHECK (email = LOWER(email))
);

CREATE TABLE books (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn             VARCHAR(13)   UNIQUE CHECK (isbn ~ '^([0-9]{9}[0-9X]|[0-9]{13})$'),
    title            VARCHAR(200)  NOT NULL CHECK (LENGTH(TRIM(title)) > 0),
    author           VARCHAR(150)  NOT NULL CHECK (LENGTH(TRIM(author)) > 0),
    genre            VARCHAR(60),
    description      VARCHAR(2000),
    published_year   INTEGER       CHECK (published_year BETWEEN 1000 AND 2100),
    total_copies     INTEGER       NOT NULL CHECK (total_copies BETWEEN 1 AND 1000),
    available_copies INTEGER       NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL,
    CONSTRAINT books_available_in_range CHECK (available_copies BETWEEN 0 AND total_copies)
);

CREATE INDEX books_title_idx ON books (LOWER(title));

CREATE TABLE loans (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id      BIGINT      NOT NULL REFERENCES books (id) ON DELETE RESTRICT,
    member_id    UUID        NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    issued_by_id UUID        REFERENCES users (id) ON DELETE SET NULL,
    issued_at    TIMESTAMPTZ NOT NULL,
    due_at       TIMESTAMPTZ NOT NULL,
    returned_at  TIMESTAMPTZ,
    CONSTRAINT loans_due_after_issue CHECK (due_at > issued_at),
    CONSTRAINT loans_returned_after_issue CHECK (returned_at IS NULL OR returned_at >= issued_at)
);

-- A member can hold at most one copy of the same book at a time.
CREATE UNIQUE INDEX loans_one_active_per_member_book ON loans (book_id, member_id) WHERE returned_at IS NULL;
CREATE INDEX loans_member_idx ON loans (member_id);
CREATE INDEX loans_active_due_idx ON loans (due_at) WHERE returned_at IS NULL;
