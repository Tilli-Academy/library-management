-- 1. "Coming soon" books: in the catalogue, but no copies yet (can't be lent).
ALTER TABLE books
    ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
        CONSTRAINT books_status_valid CHECK (status IN ('AVAILABLE', 'COMING_SOON')),
    ADD COLUMN expected_arrival DATE;

ALTER TABLE books DROP CONSTRAINT books_total_copies_check;
ALTER TABLE books
    ADD CONSTRAINT books_total_copies_range CHECK (total_copies BETWEEN 0 AND 1000),
    -- Books in stock have at least one copy; coming-soon books have none yet.
    ADD CONSTRAINT books_copies_match_status CHECK (
        (status = 'AVAILABLE' AND total_copies >= 1) OR (status = 'COMING_SOON' AND total_copies = 0));

-- 2. Members request books; other members like the request. Enough likes => the book is ordered.
CREATE TABLE book_suggestions (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200) NOT NULL CHECK (LENGTH(TRIM(title)) > 0),
    author          VARCHAR(150) NOT NULL CHECK (LENGTH(TRIM(author)) > 0),
    note            VARCHAR(500),
    requested_by_id UUID         NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    status          VARCHAR(20)  NOT NULL CHECK (status IN ('OPEN', 'APPROVED', 'DECLINED')),
    like_count      INTEGER      NOT NULL DEFAULT 0 CHECK (like_count >= 0),
    book_id         BIGINT       REFERENCES books (id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    decided_at      TIMESTAMPTZ
);

-- The same book can't be requested twice while a request for it is still open.
CREATE UNIQUE INDEX book_suggestions_one_open_per_book
    ON book_suggestions (LOWER(title), LOWER(author)) WHERE status = 'OPEN';
CREATE INDEX book_suggestions_status_likes_idx ON book_suggestions (status, like_count DESC);

CREATE TABLE book_suggestion_likes (
    suggestion_id BIGINT      NOT NULL REFERENCES book_suggestions (id) ON DELETE CASCADE,
    user_id       UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at    TIMESTAMPTZ NOT NULL,
    -- One like per member per request.
    PRIMARY KEY (suggestion_id, user_id)
);
